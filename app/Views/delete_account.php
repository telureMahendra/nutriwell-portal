    <h1>Account Deletion Request – Healthie4U</h1>
    
    <p>At Healthie4U, users can request permanent deletion of their account and associated personal data.</p>

    <h2>How to Request Account Deletion</h2>
    <p>Users can request account deletion by:</p>
    <ol>
        <li>Opening the Healthie4U app</li>
        <li>Navigating to:<br>
        <strong>Profile → Settings → Delete Account</strong></li>
    </ol>
    <p>OR</p>
    <p>Emailing us at:<br>
    <a href="mailto:support@healthie4u.in">support@healthie4u.in</a></p>

    <h2>What Data Gets Deleted</h2>
    <p>When an account deletion request is processed, the following data is permanently deleted:</p>
    <ul>
        <li>User profile information</li>
        <li>Fitness and health tracking data</li>
        <li>Activity history</li>
        <li>Preferences and settings</li>
    </ul>

    <h2>Data Retention</h2>
    <p>Certain information may be retained temporarily where required for:</p>
    <ul>
        <li>Legal compliance</li>
        <li>Fraud prevention</li>
        <li>Security purposes</li>
    </ul>
    <p>Retained data is securely deleted after the required retention period.</p>

